"""Pure helpers over Alpaca order history: bot order ids, weekly counts, exits, stop fills.

Bot orders are recognised by their client_order_id: `<prefix>-<YYYY-MM-DD>-<SYMBOL>-<kind>`.
OTO stop legs get an id generated by Alpaca, so they are attributed to the bot through
their parent (orders must be fetched with `nested=True`).
"""

from __future__ import annotations

from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from datetime import date, datetime
from typing import Literal

from tradingbot.broker.alpaca_client import EXCHANGE_TZ, OrderSnapshot
from tradingbot.risk.circuit_breakers import week_start

OrderKind = Literal["buy", "sell", "stop"]
STOP_TYPES = frozenset({"stop", "stop_limit", "trailing_stop"})
# A buy in one of these states never opened a position (unless it filled partly first).
DEAD_STATUSES = frozenset({"rejected", "canceled", "expired"})


def client_order_id(prefix: str, day: date, symbol: str, kind: OrderKind, suffix: str = "") -> str:
    """Deterministic id: Alpaca refuses a second order with the same id, so a rerun cannot duplicate it."""
    base = f"{prefix}-{day.isoformat()}-{symbol}-{kind}"
    return f"{base}-{suffix}" if suffix else base


def is_bot_order(order: OrderSnapshot, prefix: str) -> bool:
    return order.client_order_id.startswith(f"{prefix}-")


def ny_date(ts: datetime | None) -> date | None:
    return None if ts is None else ts.astimezone(EXCHANGE_TZ).date()


def flatten(orders: Iterable[OrderSnapshot]) -> Iterator[OrderSnapshot]:
    """Each order followed by its legs (works for nested and flat listings)."""
    for o in orders:
        yield o
        yield from o.legs


def bot_orders_with_legs(orders: Iterable[OrderSnapshot], prefix: str) -> Iterator[OrderSnapshot]:
    """Bot orders plus the legs of bot orders (stop legs carry Alpaca-generated ids)."""
    for o in orders:
        if is_bot_order(o, prefix):
            yield o
            yield from o.legs


def is_stop_sell(order: OrderSnapshot) -> bool:
    return order.side == "sell" and order.type in STOP_TYPES


def counts_as_new_position(order: OrderSnapshot) -> bool:
    """Filled, partly filled or still pending. Rejected / canceled / expired only count if shares filled."""
    return order.status not in DEAD_STATUSES or order.filled_qty > 0


def new_positions_this_week(orders: Iterable[OrderSnapshot], prefix: str, today: date) -> int:
    """Distinct symbols the bot bought (or is buying) in today's calendar week (New York dates)."""
    start = week_start(today)
    symbols = set()
    for o in orders:
        day = ny_date(o.submitted_at)
        if (is_bot_order(o, prefix) and o.side == "buy" and day is not None and start <= day <= today
                and counts_as_new_position(o)):
            symbols.add(o.symbol)
    return len(symbols)


def last_exits(orders: Iterable[OrderSnapshot], prefix: str) -> dict[str, date]:
    """{symbol: last New York date a bot sell (market sell or stop) filled}. Feeds the strategy's no-reentry rule."""
    out: dict[str, date] = {}
    for o in bot_orders_with_legs(orders, prefix):
        day = ny_date(o.filled_at)
        if o.side == "sell" and o.filled_qty > 0 and day is not None:
            out[o.symbol] = max(out.get(o.symbol, day), day)
    return out


@dataclass(frozen=True)
class StopFill:
    symbol: str
    qty: float
    price: float | None
    day: date


def stop_fills_since(orders: Iterable[OrderSnapshot], prefix: str, since: date) -> list[StopFill]:
    """Bot stop-losses that filled on or after `since` (reconciliation of mid-week exits)."""
    fills = []
    for o in bot_orders_with_legs(orders, prefix):
        day = ny_date(o.filled_at)
        if is_stop_sell(o) and o.filled_qty > 0 and day is not None and day >= since:
            fills.append(StopFill(o.symbol, o.filled_qty, o.filled_avg_price, day))
    return sorted(fills, key=lambda f: (f.day, f.symbol))


def open_stop_sells(open_orders: Iterable[OrderSnapshot], symbol: str) -> list[OrderSnapshot]:
    return [o for o in flatten(open_orders) if o.symbol == symbol and o.is_open and is_stop_sell(o)]
